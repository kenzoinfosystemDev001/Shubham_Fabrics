import { NextResponse } from 'next/server';
import { prisma } from '@subham/database';

export const dynamic = 'force-dynamic';

export async function GET() {
  try {
    // 1. Fetch all Challans dispatched to QC2
    const qc2Challans = await prisma.challan.findMany({
      where: {
        toDepartment: 'QC2',
      },
      include: {
        program: {
          select: {
            id: true,
            programNumber: true,
            programSerialNo: true,
            clientName: true,
            buyerName: true,
            styleCode: true,
            mainStyle: true,
            fabricName: true,
            fabricType: true,
            fabricColor: true,
            targetQuantity: true,
            deliveryDate: true,
            priority: true,
            status: true,
            quantityMeasurement: true,
            wilcomDesignNumber: true,
          },
        },
        items: true,
        issuedBy: {
          select: {
            id: true,
            fullName: true,
            username: true,
          },
        },
        receivedBy: {
          select: {
            id: true,
            fullName: true,
            username: true,
          },
        },
        inspections: {
          include: {
            inspector: {
              select: {
                id: true,
                fullName: true,
                username: true,
              },
            },
            defects: true,
          },
          orderBy: { inspectedAt: 'desc' },
          take: 1,
        },
        productionLogs: {
          where: {
            departmentCode: 'QC2',
          },
          orderBy: { recordedAt: 'desc' },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    // 2. Fetch QC2 Production Transactions for quantity aggregations
    const qc2Transactions = await prisma.productionTransaction.findMany({
      where: {
        departmentCode: 'QC2',
      },
      include: {
        operator: {
          select: {
            id: true,
            fullName: true,
            username: true,
          },
        },
      },
      orderBy: { recordedAt: 'desc' },
    });

    // 3. Fetch Defective Shelf return challans generated by QC2
    const defectiveReturns = await prisma.challan.findMany({
      where: {
        fromDepartment: 'QC2',
        toDepartment: 'STORE',
        challanType: 'DEFECTIVE_RETURN',
      },
      include: {
        items: true,
        program: {
          select: {
            programNumber: true,
            programSerialNo: true,
          },
        },
      },
      orderBy: { createdAt: 'desc' },
      take: 20,
    });

    // 4. Fetch Rework return challans generated by QC2
    const reworkReturns = await prisma.challan.findMany({
      where: {
        fromDepartment: 'QC2',
        toDepartment: 'THREAD_CUTTING',
        challanType: 'REWORK_RETURN',
      },
      include: {
        items: true,
        program: {
          select: {
            programNumber: true,
            programSerialNo: true,
          },
        },
      },
      orderBy: { createdAt: 'desc' },
      take: 20,
    });

    // 5. Aggregate metrics
    let totalPcsReceived = 0;
    let pendingInspectionCount = 0;
    let underInspectionCount = 0;
    let approvedChallansCount = 0;
    let rejectedChallansCount = 0;
    let reworkChallansCount = 0;

    for (const c of qc2Challans) {
      const challanQty = c.items.reduce((s, it) => s + (Number(it.quantity) || 0), 0);
      totalPcsReceived += challanQty;

      if (['ISSUED', 'RECEIVED'].includes(c.status)) {
        pendingInspectionCount++;
      } else if (c.status === 'UNDER_INSPECTION') {
        underInspectionCount++;
      } else if (c.status === 'QC_APPROVED' || c.status === 'COMPLETED') {
        approvedChallansCount++;
      } else if (c.status === 'QC_REJECTED') {
        rejectedChallansCount++;
      } else if (c.status === 'REWORK_REQUESTED') {
        reworkChallansCount++;
      }
    }

    let totalPassedPcs = 0;
    let totalFailedPcs = 0;
    let totalReworkPcs = 0;
    let totalInspectedPcs = 0;

    for (const tx of qc2Transactions) {
      totalPassedPcs += Number(tx.goodQuantity) || 0;
      totalFailedPcs += Number(tx.rejectQuantity) || 0;
      totalReworkPcs += Number(tx.reworkQuantity) || 0;
      totalInspectedPcs += Number(tx.inputQuantity) || 0;
    }

    const passRatePercent =
      totalInspectedPcs > 0 ? ((totalPassedPcs / totalInspectedPcs) * 100).toFixed(1) : '100.0';
    const defectRatePercent =
      totalInspectedPcs > 0 ? ((totalFailedPcs / totalInspectedPcs) * 100).toFixed(1) : '0.0';
    const reworkRatePercent =
      totalInspectedPcs > 0 ? ((totalReworkPcs / totalInspectedPcs) * 100).toFixed(1) : '0.0';

    return NextResponse.json({
      success: true,
      data: {
        summary: {
          totalChallansReceived: qc2Challans.length,
          totalPcsReceived,
          pendingInspectionCount,
          underInspectionCount,
          approvedChallansCount,
          rejectedChallansCount,
          reworkChallansCount,
          totalInspectedPcs,
          totalPassedPcs,
          totalFailedPcs,
          totalReworkPcs,
          passRatePercent,
          defectRatePercent,
          reworkRatePercent,
        },
        challans: qc2Challans,
        transactions: qc2Transactions.slice(0, 15),
        defectiveReturns,
        reworkReturns,
      },
    });
  } catch (error: any) {
    console.error('Error fetching QC2 dashboard data:', error);
    return NextResponse.json(
      { error: error.message || 'Failed to fetch QC2 dashboard data' },
      { status: 500 }
    );
  }
}
