import { NextResponse } from 'next/server';
import { prisma } from '@subham/database';
import { requireDepartment } from '@/lib/auth/department-access';

export const dynamic = 'force-dynamic';

export async function GET(request: Request) {
  const { user: authUser, response: authResponse } = await requireDepartment(request, 'QC3');
  if (!authUser) return authResponse;
  try {
    const validDepts = ['QC3', 'QCWASHING', 'QC_WASHING', 'WASHING_QC', 'QC WASHING'];

    // 1. Fetch all Challans dispatched to QC Washing
    const qcWashingChallans = await prisma.challan.findMany({
      where: {
        toDepartment: {
          in: validDepts,
        },
      },
      include: {
        program: {
          select: {
            id: true,
            programNumber: true,
            programSerialNo: true,
            clientName: true,
            buyerName: true,
            styleCode: true,
            mainStyle: true,
            fabricName: true,
            fabricType: true,
            fabricColor: true,
            targetQuantity: true,
            deliveryDate: true,
            priority: true,
            status: true,
            quantityMeasurement: true,
            wilcomDesignNumber: true,
          },
        },
        items: true,
        issuedBy: {
          select: {
            id: true,
            fullName: true,
            username: true,
          },
        },
        receivedBy: {
          select: {
            id: true,
            fullName: true,
            username: true,
          },
        },
        inspections: {
          include: {
            inspector: {
              select: {
                id: true,
                fullName: true,
                username: true,
              },
            },
            defects: true,
            parameters: true,
          },
          orderBy: { inspectedAt: 'desc' },
          take: 1,
        },
        productionLogs: {
          where: {
            departmentCode: { in: ['QC3', 'QCWASHING'] },
          },
          orderBy: { recordedAt: 'desc' },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    // 2. Fetch QC Washing Production Transactions for quantity aggregations
    const qcTransactions = await prisma.productionTransaction.findMany({
      where: {
        departmentCode: { in: ['QC3', 'QCWASHING'] },
      },
      include: {
        operator: {
          select: {
            id: true,
            fullName: true,
            username: true,
          },
        },
      },
      orderBy: { recordedAt: 'desc' },
    });

    // 3. Fetch Defective Shelf return challans generated by QC Washing
    const defectiveReturns = await prisma.challan.findMany({
      where: {
        fromDepartment: { in: ['QC3', 'QCWASHING'] },
        toDepartment: 'STORE',
        challanType: 'DEFECTIVE_RETURN',
      },
      include: {
        items: true,
        program: {
          select: {
            id: true,
            programNumber: true,
            programSerialNo: true,
            clientName: true,
            styleCode: true,
          },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    // 4. Fetch Rework Challans generated by QC Washing back to Washing
    const reworkReturns = await prisma.challan.findMany({
      where: {
        fromDepartment: { in: ['QC3', 'QCWASHING'] },
        toDepartment: 'WASHING',
        challanType: 'REWORK_HANDOFF',
      },
      include: {
        items: true,
        program: {
          select: {
            id: true,
            programNumber: true,
            programSerialNo: true,
            clientName: true,
            styleCode: true,
          },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    // 5. Aggregate KPIs
    let totalPcsReceived = 0;
    let pendingInspectionCount = 0;
    let underInspectionCount = 0;
    let approvedChallansCount = 0;
    let rejectedChallansCount = 0;
    let reworkChallansCount = 0;

    qcWashingChallans.forEach((c) => {
      const pcs = c.items.reduce((s, it) => s + (Number(it.quantity) || 0), 0);
      totalPcsReceived += pcs;

      if (['ISSUED', 'RECEIVED'].includes(c.status)) {
        pendingInspectionCount++;
      } else if (c.status === 'UNDER_INSPECTION') {
        underInspectionCount++;
      } else if (c.status === 'QC_APPROVED') {
        approvedChallansCount++;
      } else if (c.status === 'QC_REJECTED') {
        rejectedChallansCount++;
      } else if (c.status === 'REWORK_REQUESTED') {
        reworkChallansCount++;
      }
    });

    let totalInspectedPcs = 0;
    let totalPassedPcs = 0;
    let totalFailedPcs = 0;
    let totalReworkPcs = 0;

    qcTransactions.forEach((tx) => {
      totalInspectedPcs += Number(tx.inputQuantity) || 0;
      totalPassedPcs += Number(tx.goodQuantity) || 0;
      totalFailedPcs += Number(tx.rejectQuantity) || 0;
      totalReworkPcs += Number(tx.reworkQuantity) || 0;
    });

    const passRatePercent =
      totalInspectedPcs > 0
        ? ((totalPassedPcs / totalInspectedPcs) * 100).toFixed(1)
        : '100.0';

    const defectRatePercent =
      totalInspectedPcs > 0
        ? ((totalFailedPcs / totalInspectedPcs) * 100).toFixed(1)
        : '0.0';

    const reworkRatePercent =
      totalInspectedPcs > 0
        ? ((totalReworkPcs / totalInspectedPcs) * 100).toFixed(1)
        : '0.0';

    return NextResponse.json({
      success: true,
      data: {
        summary: {
          totalChallansReceived: qcWashingChallans.length,
          totalPcsReceived,
          pendingInspectionCount,
          underInspectionCount,
          approvedChallansCount,
          rejectedChallansCount,
          reworkChallansCount,
          totalInspectedPcs,
          totalPassedPcs,
          totalFailedPcs,
          totalReworkPcs,
          passRatePercent,
          defectRatePercent,
          reworkRatePercent,
        },
        challans: qcWashingChallans,
        defectiveReturns,
        reworkReturns,
        transactions: qcTransactions,
      },
    });
  } catch (error: any) {
    console.error('Error loading QC Washing dashboard data:', error);
    return NextResponse.json(
      { error: error.message || 'Failed to load QC Washing dashboard' },
      { status: 500 }
    );
  }
}
